def set_seed(seed: int) -> None:
    random.seed(seed)
    np.random.seed(seed)
    torch.manual_seed(seed)
    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


def resolve_device(device_str: str) -> torch.device:
    if device_str == "auto":
        return torch.device("cuda:0" if torch.cuda.is_available() else "cpu")
    if "cuda" in device_str and not torch.cuda.is_available():
        return torch.device("cpu")
    return torch.device(device_str)


def _resolve_path(base_path: Path, path: Path) -> Path:
    return path if path.is_absolute() else base_path / path


def _infer_use_static_features(model_path: Path, user_choice: bool | None) -> bool:
    if user_choice is not None:
        return user_choice
    return model_path.name.lower() == "cldnet" or "static" in model_path.name.lower()


def _load_reduced_trajectory(
    data_root: Path,
    traj_id: int,
    use_static_features: bool,
) -> tuple[np.ndarray, np.ndarray, np.ndarray]:
    flow = np.load(data_root / f"flow_variables_traj{traj_id}.npy", mmap_mode="r")
    coords = np.load(data_root / f"coords_traj{traj_id}.npy", mmap_mode="r")
    rain = np.load(data_root / f"rain_source_traj{traj_id}.npy", mmap_mode="r")
    if use_static_features:
        static_path = data_root / f"static_features_traj{traj_id}.npy"
        if not static_path.exists():
            raise FileNotFoundError(f"Missing static features for traj {traj_id}: {static_path}")
        static = np.load(static_path, mmap_mode="r")
        coords = np.concatenate([coords, static], axis=-1)
    return flow, coords, rain


def _list_trajectory_ids(data_root: Path) -> list[int]:
    traj_ids: list[int] = []
    for path in data_root.glob("rain_source_traj*.npy"):
        match = re.search(r"traj(\d+)\.npy$", path.name)
        if match is not None:
            traj_ids.append(int(match.group(1)))
    traj_ids = sorted(set(traj_ids))
    if not traj_ids:
        raise FileNotFoundError(f"No rain_source_traj*.npy files found in {data_root}")
    return traj_ids


def _select_background_traj_id(
    traj_ids: list[int],
    target_traj_id: int,
    requested_traj_id: int | None,
) -> int:
    if requested_traj_id is not None:
        if requested_traj_id not in traj_ids:
            raise ValueError(f"Requested background traj id {requested_traj_id} is not available")
        return requested_traj_id

    ordered = sorted(traj_ids)
    for traj_id in ordered:
        if traj_id > target_traj_id:
            return traj_id
    for traj_id in ordered:
        if traj_id != target_traj_id:
            return traj_id
    raise ValueError("Need at least two distinct trajectories to choose a background rain source")


def _build_coords(h_dim: int, w_dim: int) -> np.ndarray:
    x = 2.0 * (np.arange(w_dim, dtype=np.float32) / w_dim - 0.5)
    aspect = h_dim / float(w_dim)
    y = 2.0 * (np.arange(h_dim, dtype=np.float32) / h_dim - 0.5) * aspect
    x_coords = np.tile(x, h_dim)
    y_coords = np.repeat(y, w_dim)
    return np.stack([x_coords, y_coords], axis=1)[None, :, :].astype(np.float32)


def _resolve_scatter_indices(valid_mask: np.ndarray, h_dim: int, w_dim: int, coords: np.ndarray) -> np.ndarray:
    mask_indices = np.flatnonzero(valid_mask.reshape(-1).astype(bool))
    n_reduced = int(coords.shape[1])
    if mask_indices.size < n_reduced:
        raise ValueError(f"Mask points {mask_indices.size} < reduced points {n_reduced}")
    if mask_indices.size == n_reduced:
        return mask_indices

    full_coords = _build_coords(h_dim, w_dim).reshape(-1, 2).astype(np.float16)
    masked_coords = full_coords[mask_indices]
    reduced_xy = coords[0, :, :2].astype(np.float16, copy=False)

    coord_to_flat: dict[tuple[float, float], int] = {}
    for idx, xy in zip(mask_indices, masked_coords):
        coord_to_flat[(float(xy[0]), float(xy[1]))] = int(idx)

    scatter_indices = np.empty(n_reduced, dtype=np.int64)
    for j, xy in enumerate(reduced_xy):
        key = (float(xy[0]), float(xy[1]))
        flat_idx = coord_to_flat.get(key)
        if flat_idx is None:
            raise ValueError(f"Could not map reduced coord {key} at index {j}")
        scatter_indices[j] = flat_idx
    return scatter_indices


def _flatten_obs(obs: np.ndarray) -> np.ndarray:
    if obs.ndim != 4:
        raise ValueError(f"Expected observations with shape (N, T, K, C); got {obs.shape}")
    return obs.reshape(obs.shape[0], obs.shape[1], -1)


def _normalize(x: torch.Tensor, mean: torch.Tensor | None, std: torch.Tensor | None) -> torch.Tensor:
    if mean is None or std is None:
        return x
    view_shape = (1,) * (x.ndim - 1) + (mean.shape[0],)
    return (x - mean.reshape(view_shape)) / std.reshape(view_shape)


def _denormalize(x: torch.Tensor, mean: torch.Tensor | None, std: torch.Tensor | None) -> torch.Tensor:
    if mean is None or std is None:
        return x
    view_shape = (1,) * (x.ndim - 1) + (mean.shape[0],)
    return x * std.reshape(view_shape) + mean.reshape(view_shape)


def _relative_l2_error(truth: np.ndarray, pred: np.ndarray) -> np.ndarray:
    truth_flat = truth.reshape(truth.shape[0], -1)
    pred_flat = pred.reshape(pred.shape[0], -1)
    valid = np.isfinite(truth_flat) & np.isfinite(pred_flat)
    denom = np.linalg.norm(np.where(valid, truth_flat, 0.0), axis=1) + 1e-12
    return np.linalg.norm(np.where(valid, pred_flat - truth_flat, 0.0), axis=1) / denom


def _relative_l2_scalar(truth: np.ndarray, pred: np.ndarray) -> float:
    truth_flat = np.asarray(truth, dtype=np.float32).reshape(-1)
    pred_flat = np.asarray(pred, dtype=np.float32).reshape(-1)
    valid = np.isfinite(truth_flat) & np.isfinite(pred_flat)
    if not np.any(valid):
        return float("nan")
    truth_valid = truth_flat[valid]
    pred_valid = pred_flat[valid]
    return float(np.linalg.norm(pred_valid - truth_valid) / (np.linalg.norm(truth_valid) + 1e-12))


def _r2_scalar(truth: np.ndarray, pred: np.ndarray) -> float:
    truth_flat = np.asarray(truth, dtype=np.float32).reshape(-1)
    pred_flat = np.asarray(pred, dtype=np.float32).reshape(-1)
    valid = np.isfinite(truth_flat) & np.isfinite(pred_flat)
    if not np.any(valid):
        return float("nan")

    truth_valid = truth_flat[valid]
    pred_valid = pred_flat[valid]
    ss_res = float(np.sum((pred_valid - truth_valid) ** 2))
    ss_tot = float(np.sum((truth_valid - truth_valid.mean()) ** 2))
    if ss_tot <= 0.0:
        return float("nan")
    return float(1.0 - ss_res / ss_tot)


def _trajectory_metrics(truth: np.ndarray, pred: np.ndarray) -> tuple[float, float, float]:
    truth_flat = np.asarray(truth, dtype=np.float32).reshape(-1)
    pred_flat = np.asarray(pred, dtype=np.float32).reshape(-1)
    valid = np.isfinite(truth_flat) & np.isfinite(pred_flat)
    if not np.any(valid):
        return float("nan"), float("nan"), float("nan")

    truth_valid = truth_flat[valid]
    pred_valid = pred_flat[valid]
    error = pred_valid - truth_valid
    rmse = float(np.sqrt(np.mean(error**2)))
    truth_rms = float(np.sqrt(np.mean(truth_valid**2)))
    rel_rmse = float(rmse / (truth_rms + 1e-12))
    ss_res = float(np.sum(error**2))
    ss_tot = float(np.sum((truth_valid - truth_valid.mean()) ** 2))
    r2 = float(1.0 - ss_res / ss_tot) if ss_tot > 0.0 else float("nan")
    return rel_rmse, rmse, r2


def _load_ldnet_model(
    *,
    opt: argparse.Namespace,
    device: torch.device,
    dim_u: int,
    dim_x: int,
    dim_y: int,
) -> EfficientFourierLDNN:
    model = EfficientFourierLDNN(
        opt.fourier_mapping_size,
        [opt.num_latent_states + dim_u] + opt.NN_dyn_depth * [opt.NN_dyn_width] + [opt.num_latent_states],
        [opt.num_latent_states + dim_x] + opt.NN_rec_depth * [opt.NN_rec_width] + [dim_y],
        activation=opt.activation,
        kernel_initializer=opt.kernel_initializer,
        chunk_size=opt.chunk_size,
    )

    model_dir = opt.base_path / opt.model_path
    if opt.dyn_checkpoint is not None and opt.rec_checkpoint is not None:
        dyn_ckpt = _resolve_path(opt.base_path, opt.dyn_checkpoint)
        rec_ckpt = _resolve_path(opt.base_path, opt.rec_checkpoint)
        b_ckpt = _resolve_path(opt.base_path, opt.B_checkpoint) if opt.B_checkpoint is not None else None
    else:
        dyn_ckpt = model_dir / f"dyn_{opt.checkpoint_epoch}.ckpt"
        rec_ckpt = model_dir / f"rec_{opt.checkpoint_epoch}.ckpt"
        b_ckpt = model_dir / f"B_{opt.checkpoint_epoch}.ckpt"

    model.dyn.load_state_dict(torch.load(dyn_ckpt, map_location="cpu", weights_only=False))
    model.rec.load_state_dict(torch.load(rec_ckpt, map_location="cpu", weights_only=False))
    if b_ckpt is not None and b_ckpt.exists():
        model.B.load_state_dict(torch.load(b_ckpt, map_location="cpu", weights_only=False))

    model.to(device)
    model.eval()
    return model


def _load_encoder(checkpoint_path: Path, device: torch.device) -> tuple[TimeSeriesLSTM, dict[str, torch.Tensor | None], bool]:
    ckpt = torch.load(checkpoint_path, map_location="cpu", weights_only=False)
    config = ckpt["model_config"]
    model = TimeSeriesLSTM(
        input_size=int(config["input_size"]),
        hidden_size=int(config["hidden_size"]),
        output_size=int(config["output_size"]),
        num_layers=int(config["num_layers"]),
        dropout=float(config["dropout"]),
    )
    model.load_state_dict(ckpt["model_state_dict"])
    model.to(device)
    model.eval()

    stats = ckpt.get("stats", {})
    obs_mean = stats.get("obs_mean")
    obs_std = stats.get("obs_std")
    latent_mean = stats.get("latent_mean")
    latent_std = stats.get("latent_std")

    def _maybe_tensor(value):
        if value is None:
            return None
        if isinstance(value, torch.Tensor):
            return value.float()
        return torch.as_tensor(value, dtype=torch.float32)

    return model, {
        "obs_mean": _maybe_tensor(obs_mean),
        "obs_std": _maybe_tensor(obs_std),
        "latent_mean": _maybe_tensor(latent_mean),
        "latent_std": _maybe_tensor(latent_std),
    }, bool(ckpt.get("normalize", False))


def _ensemble_score_posterior(
    prior: torch.Tensor,
    obs_latent: torch.Tensor,
    *,
    time_steps: int,
    obs_sigma: float,
    latent_scaling: float,
    eps_alpha: float,
    generator: torch.Generator,
) -> torch.Tensor:
    device = prior.device
    dtype = prior.dtype
    prior_scaled = prior * latent_scaling
    obs_scaled = obs_latent * latent_scaling

    ensemble_size, latent_dim = prior_scaled.shape
    xt = torch.randn((ensemble_size, latent_dim), device=device, dtype=dtype, generator=generator)

    def cond_alpha(t: float) -> float:
        return 1.0 - (1.0 - eps_alpha) * t

    def cond_sigma_sq(t: float) -> float:
        return max(t, 1e-6)

    def f_func(t: float) -> float:
        alpha_t = cond_alpha(t)
        return -(1.0 - eps_alpha) / alpha_t

    def g_sq(t: float) -> float:
        sigma2_t = cond_sigma_sq(t)
        return max(1e-12, 1.0 - 2.0 * f_func(t) * sigma2_t)

    dt = 1.0 / float(time_steps)
    t = 1.0
    for _ in range(time_steps):
        alpha_t = cond_alpha(t)
        sigma2_t = cond_sigma_sq(t)
        f_t = f_func(t)
        diffuse_sq = g_sq(t)
        diffuse = math.sqrt(diffuse_sq)
        tau = 1.0 - t
        score_likelihood = tau * (-(xt - obs_scaled.unsqueeze(0)) / (obs_sigma**2 + 1e-12))
        drift = f_t * xt + diffuse_sq * ((xt - alpha_t * prior_scaled) / sigma2_t) - diffuse_sq * score_likelihood
        xt = xt - dt * drift + math.sqrt(dt) * diffuse * torch.randn(
            xt.shape, device=device, dtype=dtype, generator=generator
        )
        t = max(0.0, t - dt)

    return xt / latent_scaling


def _series_to_grid(series: np.ndarray, coarse_shape: tuple[int, int], coarse_valid_flat: np.ndarray) -> np.ndarray:
    grid = np.full((series.shape[0], *coarse_shape), np.nan, dtype=np.float32)
    grid.reshape(series.shape[0], -1)[:, coarse_valid_flat] = series.astype(np.float32, copy=False)
    return grid


def _make_map_gif(
    *,
    time: np.ndarray,
    truth_grid: np.ndarray,
    obs_coords: np.ndarray,
    obs_values: np.ndarray,
    obs_err_values: np.ndarray,
    forecast_grid: np.ndarray,
    assim_grid: np.ndarray,
    left_vmin: float,
    left_vmax: float,
    err_vmax: float,
    extent: tuple[float, float, float, float],
    out_path: Path,
    fps: int,
    stride: int,
) -> None:
    time = np.asarray(time)
    stride = max(1, int(stride))
    frame_indices = list(range(0, len(time), stride))
    if frame_indices[-1] != len(time) - 1:
        frame_indices.append(len(time) - 1)

    fig, axes = plt.subplots(2, 3, figsize=(15.0, 11.5), sharex=False, sharey=False)
    left_cmap = plt.get_cmap("Blues").copy()
    left_cmap.set_bad(color=(1.0, 1.0, 1.0, 0.0))
    err_cmap = plt.get_cmap("magma").copy()
    err_cmap.set_bad(color=(1.0, 1.0, 1.0, 0.0))

    top_titles = [
        "Truth + noisy observations",
        "Forecast from background rainfall",
        "LD-ENSF assimilation",
    ]
    bottom_titles = [
        "Observation error",
        "Forecast error",
        "Assimilation error",
    ]

    top_images: list[object] = []
    bottom_images: list[object] = []
    obs_scatter = None
    obs_err_scatter = None

    for col in range(3):
        ax_top = axes[0, col]
        ax_bottom = axes[1, col]
        ax_top.set_title(top_titles[col], fontsize=11)
        ax_bottom.set_title(bottom_titles[col], fontsize=11)
        ax_top.set_xlim(extent[0], extent[1])
        ax_top.set_ylim(extent[2], extent[3])
        ax_bottom.set_xlim(extent[0], extent[1])
        ax_bottom.set_ylim(extent[2], extent[3])
        ax_top.set_aspect("equal")
        ax_bottom.set_aspect("equal")
        ax_top.set_xticks([])
        ax_top.set_yticks([])
        ax_bottom.set_xticks([])
        ax_bottom.set_yticks([])

        if col == 0:
            top_im = ax_top.imshow(
                truth_grid[0],
                origin="lower",
                extent=extent,
                cmap=left_cmap,
                vmin=left_vmin,
                vmax=left_vmax,
                interpolation="nearest",
                aspect="equal",
            )
            obs_scatter = ax_top.scatter(
                obs_coords[:, 0],
                obs_coords[:, 1],
                c=obs_values[0],
                cmap=left_cmap,
                vmin=left_vmin,
                vmax=left_vmax,
                s=8,
                edgecolors="black",
                linewidths=0.15,
                alpha=0.95,
            )
            obs_err_scatter = ax_bottom.scatter(
                obs_coords[:, 0],
                obs_coords[:, 1],
                c=obs_err_values[0],
                cmap=err_cmap,
                vmin=0.0,
                vmax=err_vmax,
                s=8,
                edgecolors="black",
                linewidths=0.15,
                alpha=0.95,
            )
            bottom_im = obs_err_scatter
        elif col == 1:
            top_im = ax_top.imshow(
                forecast_grid[0],
                origin="lower",
                extent=extent,
                cmap=left_cmap,
                vmin=left_vmin,
                vmax=left_vmax,
                interpolation="nearest",
                aspect="equal",
            )
            bottom_im = ax_bottom.imshow(
                np.abs(forecast_grid[0] - truth_grid[0]),
                origin="lower",
                extent=extent,
                cmap=err_cmap,
                vmin=0.0,
                vmax=err_vmax,
                interpolation="nearest",
                aspect="equal",
            )
        else:
            top_im = ax_top.imshow(
                assim_grid[0],
                origin="lower",
                extent=extent,
                cmap=left_cmap,
                vmin=left_vmin,
                vmax=left_vmax,
                interpolation="nearest",
                aspect="equal",
            )
            bottom_im = ax_bottom.imshow(
                np.abs(assim_grid[0] - truth_grid[0]),
                origin="lower",
                extent=extent,
                cmap=err_cmap,
                vmin=0.0,
                vmax=err_vmax,
                interpolation="nearest",
                aspect="equal",
            )

        top_images.append(top_im)
        bottom_images.append(bottom_im)

    for col in range(3):
        axes[1, col].set_xlabel("x")
    for row in range(2):
        axes[row, 0].set_ylabel("y")

    suptitle = fig.suptitle("Hydro LD-ENSF comparison", fontsize=13, y=0.98)
    fig.subplots_adjust(left=0.035, right=0.995, bottom=0.06, top=0.93, wspace=0.08, hspace=0.12)

    def update(frame_idx: int):
        idx = frame_indices[frame_idx]
        suptitle.set_text(f"Hydro LD-ENSF comparison | frame {frame_idx + 1}/{len(frame_indices)} | time step {idx}")
        top_images[0].set_data(truth_grid[idx])
        if obs_scatter is not None:
            obs_scatter.set_array(obs_values[idx])
        if obs_err_scatter is not None:
            obs_err_scatter.set_array(obs_err_values[idx])

        top_images[1].set_data(forecast_grid[idx])
        bottom_images[1].set_data(np.abs(forecast_grid[idx] - truth_grid[idx]))

        top_images[2].set_data(assim_grid[idx])
        bottom_images[2].set_data(np.abs(assim_grid[idx] - truth_grid[idx]))
        artists = top_images + bottom_images
        if obs_scatter is not None:
            artists.append(obs_scatter)
        if obs_err_scatter is not None:
            artists.append(obs_err_scatter)
        return artists

    anim = mpl_animation.FuncAnimation(
        fig,
        update,
        frames=len(frame_indices),
        interval=1000.0 / max(1, fps),
        blit=False,
        repeat=True,
    )

    if mpl_animation.writers.is_available("pillow"):
        writer = mpl_animation.PillowWriter(fps=max(1, fps))
    elif mpl_animation.writers.is_available("imagemagick"):
        writer = mpl_animation.ImageMagickWriter(fps=max(1, fps))
    else:
        raise RuntimeError("No GIF writer available. Install pillow or ImageMagick.")

    anim.save(str(out_path), writer=writer, dpi=120)
    plt.close(fig)


