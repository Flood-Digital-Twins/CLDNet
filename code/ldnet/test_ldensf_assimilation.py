def main(opt: argparse.Namespace) -> None:
    set_seed(opt.seed)
    device = resolve_device(opt.device)
    da_seed = opt.seed if opt.da_seed is None else opt.da_seed

    cpu_rng = torch.Generator(device="cpu")
    cpu_rng.manual_seed(da_seed)
    device_rng = torch.Generator(device=device.type)
    device_rng.manual_seed(da_seed)

    base_path = opt.base_path
    data_root = _resolve_path(base_path, opt.data_root)
    dataset_path = _resolve_path(base_path, opt.dataset_path)
    model_path = _resolve_path(base_path, opt.model_path)
    encoder_path = _resolve_path(base_path, opt.encoder_checkpoint)
    output_dir = _resolve_path(base_path, opt.output_dir)
    output_dir.mkdir(parents=True, exist_ok=True)

    use_static_features = _infer_use_static_features(model_path, opt.use_static_features)

    dataset = torch.load(dataset_path, map_location="cpu", weights_only=False)
    obs_idx = dataset["meta"]["selected_obs_idx"]
    if isinstance(obs_idx, torch.Tensor):
        obs_idx = obs_idx.cpu().numpy()
    else:
        obs_idx = np.asarray(obs_idx)

    available_traj_ids = _list_trajectory_ids(data_root)
    background_traj_id = _select_background_traj_id(
        available_traj_ids,
        target_traj_id=opt.traj_id,
        requested_traj_id=opt.background_traj_id,
    )

    flow, coords, rain = _load_reduced_trajectory(data_root, opt.traj_id, use_static_features)
    _, _, rain_bg = _load_reduced_trajectory(data_root, background_traj_id, use_static_features)
    t_len = int(flow.shape[1])
    dim_u = int(rain.shape[-1])
    dim_y = int(flow.shape[-1])
    dim_x = int(coords.shape[-1])

    model = _load_ldnet_model(
        opt=opt,
        device=device,
        dim_u=dim_u,
        dim_x=dim_x,
        dim_y=dim_y,
    )
    encoder, enc_stats, encoder_normalized = _load_encoder(encoder_path, device)

    obs_truth = np.asarray(flow[0][:, obs_idx, :], dtype=np.float32)
    obs_noise = opt.obs_noise_std * torch.randn(obs_truth.shape, generator=cpu_rng, dtype=torch.float32)
    obs_noisy = obs_truth + obs_noise.numpy().astype(np.float32)

    obs_tensor = torch.from_numpy(obs_noisy.reshape(1, t_len, -1)).to(device)
    obs_mean = enc_stats["obs_mean"].to(device) if enc_stats["obs_mean"] is not None else None
    obs_std = enc_stats["obs_std"].to(device) if enc_stats["obs_std"] is not None else None
    latent_mean = enc_stats["latent_mean"].to(device) if enc_stats["latent_mean"] is not None else None
    latent_std = enc_stats["latent_std"].to(device) if enc_stats["latent_std"] is not None else None

    obs_tensor = _normalize(obs_tensor, obs_mean, obs_std)
    with torch.no_grad():
        obs_latent = encoder(obs_tensor).squeeze(0)
    obs_latent = _denormalize(obs_latent, latent_mean, latent_std)

    rain_tensor = torch.from_numpy(np.asarray(rain_bg, dtype=np.float32)).to(device)
    dummy_x = torch.zeros((1, t_len, 1, dim_x), dtype=torch.float32, device=device)
    x_map = np.load(data_root / f"coords_traj{opt.traj_id}.npy", mmap_mode="r")
    if use_static_features:
        static = np.load(data_root / f"static_features_traj{opt.traj_id}.npy", mmap_mode="r")
        x_map = np.concatenate([x_map, static], axis=-1)
    x_map = np.asarray(x_map, dtype=np.float32)

    mask_path = data_root / "aggregate_mask.npy"
    if not mask_path.exists():
        raise FileNotFoundError(f"Missing aggregate mask: {mask_path}")
    domain_mask = np.load(mask_path)
    if domain_mask.ndim != 2:
        raise ValueError(f"Expected aggregate mask with shape (H, W); got {domain_mask.shape}")
    h_dim, w_dim = domain_mask.shape
    scatter_indices = _resolve_scatter_indices(domain_mask, h_dim, w_dim, x_map)
    grid_to_reduced = -np.ones(h_dim * w_dim, dtype=np.int64)
    grid_to_reduced[scatter_indices] = np.arange(scatter_indices.size)

    map_stride = max(1, int(opt.map_stride))
    row_sel = np.arange(0, h_dim, map_stride, dtype=np.int64)
    col_sel = np.arange(0, w_dim, map_stride, dtype=np.int64)
    coarse_mask = domain_mask[np.ix_(row_sel, col_sel)].reshape(-1).astype(bool)
    coarse_flat = (row_sel[:, None] * w_dim + col_sel[None, :]).reshape(-1)
    coarse_reduced = grid_to_reduced[coarse_flat]
    coarse_reduced = coarse_reduced[coarse_mask]
    if coarse_reduced.size == 0:
        raise ValueError(f"Map stride {map_stride} produced no valid coarse cells.")
    coarse_shape = (row_sel.size, col_sel.size)
    coarse_valid_flat = np.flatnonzero(coarse_mask)
    coarse_coords = x_map[0, coarse_reduced, :].astype(np.float32, copy=False)
    x_map_coarse = np.broadcast_to(
        coarse_coords[None, None, :, :],
        (1, t_len, coarse_coords.shape[0], coarse_coords.shape[1]),
    ).copy()
    x_map_tensor = torch.from_numpy(x_map_coarse).to(device)

    x_vals = 2.0 * (col_sel.astype(np.float32) / float(w_dim) - 0.5)
    aspect = float(h_dim) / float(w_dim)
    y_vals = 2.0 * (row_sel.astype(np.float32) / float(h_dim) - 0.5) * aspect
    dx = float(np.diff(x_vals).mean()) if x_vals.size > 1 else 1.0
    dy = float(np.diff(y_vals).mean()) if y_vals.size > 1 else 1.0
    map_extent = (
        float(x_vals.min() - 0.5 * dx),
        float(x_vals.max() + 0.5 * dx),
        float(y_vals.min() - 0.5 * dy),
        float(y_vals.max() + 0.5 * dy),
    )

    with torch.no_grad():
        forecast_latent = model({"u": rain_tensor, "x": dummy_x, "dt": torch.tensor([1.0], device=device)}, device, latent_state=True)
        forecast_phys = model({"u": rain_tensor, "x": x_map_tensor, "dt": torch.tensor([1.0], device=device)}, device)

    forecast_latent = forecast_latent.squeeze(0)
    forecast_phys = forecast_phys.detach().cpu().numpy()

    state = torch.zeros(opt.ensemble_size, opt.num_latent_states, device=device)
    assim_latent_hist: list[torch.Tensor] = []
    forecast_prior_hist: list[torch.Tensor] = []

    for t in tqdm(range(t_len), desc="LD-ENSF", leave=False):
        u_t = rain_tensor[:, t, :].expand(opt.ensemble_size, -1)
        with torch.no_grad():
            state = state + model.dyn(torch.cat([u_t, state], dim=1))
        forecast_prior_hist.append(state.mean(dim=0).detach().cpu())

        state = _ensemble_score_posterior(
            prior=state,
            obs_latent=obs_latent[t],
            time_steps=opt.euler_steps,
            obs_sigma=opt.obs_sigma,
            latent_scaling=opt.latent_scaling,
            eps_alpha=opt.eps_alpha,
            generator=device_rng,
        )
        assim_latent_hist.append(state.mean(dim=0).detach().cpu())

    assim_latent = torch.stack(assim_latent_hist, dim=0).numpy()
    forecast_prior_latent = torch.stack(forecast_prior_hist, dim=0).numpy()

    truth_phys = np.asarray(flow[0][:, coarse_reduced, :], dtype=np.float32)
    truth_grid = _series_to_grid(truth_phys[:, :, 0], coarse_shape, coarse_valid_flat)
    forecast_grid = _series_to_grid(forecast_phys[0, :, :, 0], coarse_shape, coarse_valid_flat)

    assim_phys = np.empty_like(forecast_phys, dtype=np.float32)
    x_map_single = x_map_tensor[:, 0, :, :]
    with torch.no_grad():
        for t in range(t_len):
            latent_t = torch.from_numpy(assim_latent[t : t + 1]).to(device)
            pred_t = model._decode_points(x_map_single, latent_t, chunk_size=model.chunk_size)
            assim_phys[0, t] = pred_t[0].detach().cpu().numpy()
    assim_grid = _series_to_grid(assim_phys[0, :, :, 0], coarse_shape, coarse_valid_flat)

    obs_values = obs_noisy[:, :, 0].astype(np.float32, copy=False)
    obs_truth_values = obs_truth[:, :, 0].astype(np.float32, copy=False)
    obs_err_values = np.abs(obs_values - obs_truth_values).astype(np.float32, copy=False)
    obs_coords = x_map[0, obs_idx, :2].astype(np.float32, copy=False)

    sample_idx = np.linspace(0, t_len - 1, min(t_len, 12), dtype=int)
    truth_sample = truth_grid[sample_idx].ravel()
    forecast_sample = forecast_grid[sample_idx].ravel()
    assim_sample = assim_grid[sample_idx].ravel()
    left_samples = np.concatenate([truth_sample, forecast_sample, assim_sample])
    left_samples = left_samples[np.isfinite(left_samples)]
    if left_samples.size == 0:
        left_vmin, left_vmax = 0.0, 1.0
    else:
        left_vmin = min(0.0, float(np.nanpercentile(left_samples, 0.5)))
        left_vmax = float(np.nanpercentile(left_samples, 99.5))
        if not np.isfinite(left_vmax) or left_vmax <= left_vmin:
            left_vmin, left_vmax = 0.0, max(1.0, float(np.nanmax(left_samples)))

    err_samples = np.concatenate(
        [
            np.abs(forecast_grid[sample_idx] - truth_grid[sample_idx]).ravel(),
            np.abs(assim_grid[sample_idx] - truth_grid[sample_idx]).ravel(),
            obs_err_values[sample_idx].ravel(),
        ]
    )
    err_samples = err_samples[np.isfinite(err_samples)]
    if err_samples.size == 0:
        err_vmax = 1.0
    else:
        err_vmax = float(np.nanpercentile(err_samples, 99.5))
        if not np.isfinite(err_vmax) or err_vmax <= 0:
            err_vmax = max(1.0, float(np.nanmax(err_samples)))

    final_forecast_err = _relative_l2_scalar(truth_grid[-1], forecast_grid[-1])
    final_assim_err = _relative_l2_scalar(truth_grid[-1], assim_grid[-1])
    final_forecast_r2 = _r2_scalar(truth_grid[-1], forecast_grid[-1])
    final_assim_r2 = _r2_scalar(truth_grid[-1], assim_grid[-1])
    traj_forecast_rel_rmse, traj_forecast_rmse, traj_forecast_r2 = _trajectory_metrics(truth_grid, forecast_grid)
    traj_assim_rel_rmse, traj_assim_rmse, traj_assim_r2 = _trajectory_metrics(truth_grid, assim_grid)

    print(f"Trajectory id: {opt.traj_id}")
    print(f"Forecast rain trajectory id: {background_traj_id}")
    print(f"Observation points: {len(obs_idx)}")
    print(f"Using static features: {use_static_features}")
    print(f"DA seed: {da_seed}")
    print(f"Final relative L2 error - forecast: {final_forecast_err:.4f}")
    print(f"Final relative L2 error - assimilation: {final_assim_err:.4f}")
    print(f"Final R^2 - forecast: {final_forecast_r2:.4f}")
    print(f"Final R^2 - assimilation: {final_assim_r2:.4f}")
    print(f"Trajectory relative RMSE - forecast: {traj_forecast_rel_rmse:.4f}")
    print(f"Trajectory relative RMSE - assimilation: {traj_assim_rel_rmse:.4f}")
    print(f"Trajectory R^2 - forecast: {traj_forecast_r2:.4f}")
    print(f"Trajectory R^2 - assimilation: {traj_assim_r2:.4f}")
    print(f"Encoder normalized input: {encoder_normalized}")

    npz_path = output_dir / f"traj_{opt.traj_id}_ldensf_results.npz"
    np.savez_compressed(
        npz_path,
        truth_grid=truth_grid,
        forecast_grid=forecast_grid,
        assim_grid=assim_grid,
        obs_coords=obs_coords,
        obs_values=obs_values,
        obs_truth_values=obs_truth_values,
        obs_err_values=obs_err_values,
        forecast_latent=forecast_latent.detach().cpu().numpy(),
        forecast_prior_latent=forecast_prior_latent,
        assim_latent=assim_latent,
        forecast_rain_traj_id=int(background_traj_id),
        final_forecast_err=final_forecast_err,
        final_assim_err=final_assim_err,
        final_forecast_r2=final_forecast_r2,
        final_assim_r2=final_assim_r2,
        traj_forecast_rel_rmse=traj_forecast_rel_rmse,
        traj_assim_rel_rmse=traj_assim_rel_rmse,
        traj_forecast_rmse=traj_forecast_rmse,
        traj_assim_rmse=traj_assim_rmse,
        traj_forecast_r2=traj_forecast_r2,
        traj_assim_r2=traj_assim_r2,
        obs_idx=obs_idx,
    )

    gif_path = output_dir / f"traj_{opt.traj_id}_ldensf.gif"
    _make_map_gif(
        time=np.arange(t_len),
        truth_grid=truth_grid,
        obs_coords=obs_coords,
        obs_values=obs_values,
        obs_err_values=obs_err_values,
        forecast_grid=forecast_grid,
        assim_grid=assim_grid,
        left_vmin=left_vmin,
        left_vmax=left_vmax,
        err_vmax=err_vmax,
        extent=map_extent,
        out_path=gif_path,
        fps=opt.gif_fps,
        stride=opt.gif_stride,
    )

    print(f"Saved results to: {npz_path}")
    print(f"Saved GIF to: {gif_path}")


if __name__ == "__main__":
    main(create_options())
