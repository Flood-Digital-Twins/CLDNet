"""
Seeded LD-ENSF-style assimilation test for hydro_surrogate_light.

Pipeline:
1. Load the raw trajectory and the observation key points generated by
   `create_ldensf_dataset.py`.
2. Encode the noisy observations with the trained LSTM.
3. Propagate the LDNet latent dynamics forward and apply an LD-ENSF-style
   ensemble score update in latent space at every time step.
4. Render a domain GIF with truth, forecast, and assimilation panels.
"""

